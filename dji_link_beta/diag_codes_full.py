def diagcode_text(code):
    """DiagnosticCode int -> best human text (tips > capsule > checklist), or None."""
    e = DIAGCODE_TEXT.get(code)
    if not e:
        return None
    for k in ("tips", "capsule", "checklist"):
        if k in e:
            return e[k]
    return None


def diagcode_info(code):
    """DiagnosticCode int -> full entry dict (mod, lvl, texts), or None."""
    return DIAGCODE_TEXT.get(code)


def hms_alarmid_to_diagcode(alarm_id):
    """HMS 8-hex alarm-id (str or int) -> list of DiagnosticCode ints ([] if unknown)."""
    if isinstance(alarm_id, int):
        alarm_id = format(alarm_id, "08X")
    return HMS_ALARMID_TO_DIAGCODE.get(str(alarm_id).upper(), [])


def hms_alarmid_text(alarm_id):
    """HMS 8-hex alarm-id -> list of (code, text) for each mapped DiagnosticCode."""
    return [(c, diagcode_text(c)) for c in hms_alarmid_to_diagcode(alarm_id)]


def redundancy_error(dev_type, err_type):
    """(dev_type, err_type) -> the REDUNDANCY_ERRORS entry, or None."""
    for e in REDUNDANCY_ERRORS:
        if e["dev_type"] == dev_type and e["err_type"] == err_type:
            return e
    return None
