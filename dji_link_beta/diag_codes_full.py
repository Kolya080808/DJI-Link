"""
DJI Fly (dji.go.v5 v1.21.4) — FULL diagnostic / error / status code tables (WM160-oriented).

Companion to diag_codes.py. diag_codes.py holds the native-lib value->DiagnosticCode
tables (FCDiagnosticsUtility::CodeFor* : MotorStartFailureError/MotorStopReason/
IMUFailureReason/GoHomeStage). THIS file adds:
  1. DIAGCODE_TEXT       — DiagnosticCode(int) -> human text + severity. RECOVERED LOCALLY.
  2. HMS_ALARMID_TO_DIAGCODE — HMS 8-hex alarm-id -> DiagnosticCode(s).
  3. REDUNDANCY_ERRORS   — FC sensor/calibration error DB (dev_type,err_type).
  4. ERROR_ENUM_CATALOG  — other error/status enums + where their value tables live.

KEY FINDING: DiagnosticCode text is 100% LOCAL (on-device), NOT server-fetched.
The pipeline the app uses:
  drone HMS alarm-id (8-hex)  --hms2sdkcode.json-->  DiagnosticCode(int)
  DiagnosticCode(int)         --config DSL (baked in classes_0855200c.dex)-->  resName
  resName (e.g. "fpv_tips_...")  --strings.xml-->  localized text
The config DSL is com.uav.diagnostic.config.module.<Sub>CodesKt.a(CodesBuilder): each
code is registered with checklist/capsule/tips string-resource ids and a severity
Level (Red/Yellow/White/Transparent). Table 1 below is that mapping, resolved to the
English strings.xml locale. (The only DJI *server* URLs in this area are FlySafe/GEO
zone data at flysafe-api.dji.com — not diagnostic text.)

Coverage: 743 DiagnosticCodes parsed from the config; 718 have at least one
bundled English text (414 with a full "tips" sentence). Codes without a text are
kept with their module+severity (their resName had no English string in this build).

WM160 (Mavic Mini 1, ProductType 0x3b) relevance: the APK ships ONE table set for every
drone the app supports; these FC/HMS diagnostic codes are firmware-generic, so WM160 can
emit any subset its firmware raises. WM160 lacks forward/backward/upward obstacle vision
(only downward VPS), RTK, and multi-battery — Vision/RTK/dual-battery codes are largely
unreachable on it. Nothing here is per-model, so no model filtering is encoded.

Self-contained: plain dicts + lookup helpers, no project imports. Provenance cited per
table. Unknown texts are left ABSENT, never guessed.
"""

